CREATE INDEX IF NOT EXISTS idx_log_isin ON control.ingestion_log (isin);
CREATE INDEX IF NOT EXISTS idx_log_status ON control.ingestion_log (status);
CREATE INDEX IF NOT EXISTS idx_log_step ON control.ingestion_log (step, created_at);
CREATE INDEX IF NOT EXISTS idx_log_created_brin ON control.ingestion_log
  USING brin (created_at) WITH (pages_per_range = 32);

-- Retention (§P2 — no partitioning for this table at current volume; quarterly chunked DELETE instead)
COMMENT ON TABLE control.ingestion_log IS
  'Append-only P1 log. Retention: quarterly DELETE WHERE created_at < now() - interval ''24 months'' '
  'in 100K-row chunks + VACUUM. Upgrade to PARTITION BY RANGE(created_at) only if this crosses ~50M rows.';

-- -----------------------------------------------------------------------------
-- control.nav_sources — 3,726 rows, Morningstar ms_id + date range + status
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS control.nav_sources (
    isin              varchar(12) PRIMARY KEY,
    source             text,        -- MORNINGSTAR / CNMV / NOT_FOUND
    source_id            text,        -- internal source ID, e.g. F0GBR04S23 in Morningstar
    first_nav_date         date,
    last_nav_date           date,
    nav_count                 integer,
    discovered_at             date,
    last_checked               date,
    status                     text CHECK (status IN ('OK','NOT_FOUND','ERROR')),
    data_status                 text DEFAULT 'OK'
        -- STALE_FROZEN added 2026-09-19: confirmed missing from the original CHECK list, found
        -- against the live server. Legitimate value, not a data-quality issue — added by the
        -- FIX-FROZEN-NAV project (nav_discovery.py auto-detects funds frozen >365 days, e.g. the
        -- Russia/EE sanctions cohort) after this table's original schema reference was current.
        -- The other 4 values (FORCE_REFRESH/RECALCULATE_MONTHLY/RECALCULATE_METRICS/PENDING) are
        -- kept even though only OK/STALE_FROZEN appear in today's snapshot — they're legitimate
        -- transient states in the documented nav_discovery state machine, not everything that
        -- happens to be live right now.
        CHECK (data_status IN ('OK','FORCE_REFRESH','RECALCULATE_MONTHLY','RECALCULATE_METRICS','PENDING','STALE_FROZEN'))
);

CREATE INDEX IF NOT EXISTS idx_nav_sources_status ON control.nav_sources (status);
CREATE INDEX IF NOT EXISTS idx_nav_sources_source ON control.nav_sources (source);
CREATE INDEX IF NOT EXISTS idx_nav_sources_data_status ON control.nav_sources (data_status);

-- -----------------------------------------------------------------------------
-- control.benchmark_ms_checks — negative cache for proyecto1/src/loaders/benchmark_loader.py.
-- One row per ISIN for which Morningstar returned NO benchmark (or a rejected placeholder). The
-- loader's `--mode update` skips an ISIN until next_check_at, backing off per consecutive miss
-- (shared/config.py BENCH_NEGATIVE_BACKOFF_DAYS). PG-only, no SQLite source (like regime_history).
-- Deliberately NOT a sentinel row in silver.fund_benchmarks: pipeline.py prefers any MORNINGSTAR
-- row over a KIID row, so a "no benchmark" marker there would displace real KIID data.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS control.benchmark_ms_checks (
    isin              varchar(12) PRIMARY KEY,
    n_misses           integer     NOT NULL CHECK (n_misses >= 1),
    last_checked_at     timestamptz NOT NULL,
    next_check_at        timestamptz NOT NULL,

    CONSTRAINT benchmark_ms_checks_isin_fk FOREIGN KEY (isin) REFERENCES silver.fund_master (isin) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_bms_checks_next ON control.benchmark_ms_checks (next_check_at);


-- Seed-loader restart bookkeeping (§P3 "Restart semantics"). Table/partition-granularity resume —
-- a crash mid-COPY resumes at the failed unit, not a full re-run of the 55-90 min load. Dropped or
-- archived once the reconciliation gate passes.
CREATE TABLE IF NOT EXISTS control.seed_progress (
    target_table    text PRIMARY KEY,   -- e.g. 'gold.fmts_p_sharpe', 'bronze.fund_nav_daily'
    status           text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','done')),
    completed_at       timestamptz
);

-- Orphan quarantine tables (§P3 "Orphan pre-scan" + Reconciliation gate check (d)). One per
-- FK-bearing target whose SQLite-side orphan set is identified BEFORE any COPY runs, so orphans
-- are routed here in the same pass instead of being discovered at VALIDATE CONSTRAINT time after
-- a 40-minute load. `LIKE ... INCLUDING ALL` never copies FOREIGN KEY constraints (PG semantics),
-- so no explicit "drop the FK" step is needed.
--
-- gold.fund_metric_timeseries is the KNOWN risk (its FK was lost in the live v29 SQLite rebuild —
-- see 30_gold.sql comment); the other eight are covered on the same principle, since the pre-scan
-- is cheap and the alternative (discovering an orphan there instead, unquarantined) is not.
DO $$
DECLARE
  targets text[][] := ARRAY[
    ARRAY['gold',   'fund_metric_timeseries'],
    ARRAY['gold',   'fund_metrics'],
    ARRAY['gold',   'fund_metric_alerts'],
    ARRAY['gold',   'fund_scores'],
    ARRAY['gold',   'portfolio_weights'],
    ARRAY['bronze', 'fund_nav_daily'],
    ARRAY['bronze', 'fund_nav_monthly'],
    ARRAY['control','fund_metric_state'],
    ARRAY['control','audit_finding']
  ];
  i int;
BEGIN
  FOR i IN 1 .. array_length(targets, 1) LOOP
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS control.quarantine_%s_orphans (LIKE %I.%I INCLUDING ALL)',
      targets[i][2], targets[i][1], targets[i][2]
    );
  END LOOP;
END $$;

COMMENT ON TABLE control.quarantine_fund_metric_timeseries_orphans IS
  'Rows from the SQLite source whose isin has no matching silver.fund_master row, routed here '
  'during the seed COPY (§P3 step 3/5) instead of reaching the FK-bearing target. Gate check (d) '
  'requires this count to equal the SQLite-side pre-scan count exactly.';


-- =============================================================================
-- Automated maintenance apparatus (§P2 "Clustering", "Bloat monitoring")
-- One named entry point (control.run_monthly_maintenance, defined in 40_matviews.sql once
-- refresh_gold_matviews() also exists) wraps everything below plus the disk-headroom pre-flight.
-- =============================================================================

-- --- Cluster health: measured and self-triggering, not a calendar reminder ---
CREATE OR REPLACE VIEW control.v_cluster_health AS
SELECT schemaname, tablename, correlation,
       correlation < 0.90 AS needs_cluster
FROM   pg_stats
WHERE  attname = 'isin'
  AND ( (schemaname, tablename) IN (('bronze','fund_nav_daily'), ('gold','fund_metrics'))
        OR tablename LIKE 'fmts_p_%' );

CREATE OR REPLACE FUNCTION control.maintain_clusters(p_threshold numeric DEFAULT 0.90)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  r record;
  t0 timestamptz;
BEGIN
  FOR r IN SELECT schemaname, tablename FROM control.v_cluster_health WHERE needs_cluster LOOP
    t0 := clock_timestamp();
    EXECUTE format('CLUSTER %I.%I', r.schemaname, r.tablename);
    EXECUTE format('ANALYZE %I.%I', r.schemaname, r.tablename);
    INSERT INTO control.p2_pipeline_log (step, status, message)
      VALUES ('CLUSTER_MAINT', 'OK',
              format('%s.%s reclustered in %s', r.schemaname, r.tablename,
                     clock_timestamp() - t0));
  END LOOP;
  IF NOT FOUND THEN
    INSERT INTO control.p2_pipeline_log (step, status, message)
      VALUES ('CLUSTER_MAINT', 'SKIP', 'nothing below correlation threshold');
  END IF;
END $$;

-- --- Bloat: measurable via pgstattuple; small tables auto-remediate, big tables alert only ---
CREATE OR REPLACE VIEW control.v_bloat_health AS
SELECT schemaname, tablename,
       pg_table_size(format('%I.%I', schemaname, tablename)::regclass) AS table_size_bytes,
       (pgstattuple(format('%I.%I', schemaname, tablename)::regclass)).dead_tuple_percent,
       (pgstattuple(format('%I.%I', schemaname, tablename)::regclass)).dead_tuple_percent > 15
         AS needs_attention
FROM   pg_tables
WHERE  schemaname IN ('bronze','silver','gold','control')
  -- exclude the two big tables from the routine (monthly) pass — a pgstattuple full scan of them
  -- is itself an IO event worth budgeting quarterly, not a free monthly check (§P2 index plan)
  AND NOT (schemaname = 'gold' AND tablename LIKE 'fmts_p_%')
  AND NOT (schemaname = 'bronze' AND tablename = 'fund_nav_daily');

CREATE OR REPLACE FUNCTION control.maintain_bloat(p_threshold numeric DEFAULT 15)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  r record;
BEGIN
  FOR r IN SELECT schemaname, tablename, table_size_bytes
           FROM control.v_bloat_health WHERE needs_attention LOOP
    IF r.table_size_bytes < 100 * 1024 * 1024 THEN   -- ~ under 100K-row-class tables
      EXECUTE format('VACUUM (FULL) %I.%I', r.schemaname, r.tablename);
      INSERT INTO control.p2_pipeline_log (step, status, message)
        VALUES ('BLOAT_AUTOVACUUM_FULL', 'OK', format('%s.%s', r.schemaname, r.tablename));
    ELSE
      INSERT INTO control.p2_pipeline_log (step, status, message)
        VALUES ('BLOAT_ALERT', 'WARN',
                format('%s.%s dead_tuple_percent > %s — see maintain_clusters()',
                       r.schemaname, r.tablename, p_threshold));
    END IF;
  END LOOP;
END $$;

-- --- DEFAULT partition: detect accumulation (CI test is the primary gate — see §5a in the plan;
-- this view is the RUNTIME backstop for a metric appearing in data without a matching code change) ---
CREATE OR REPLACE VIEW control.v_default_partition_metrics AS
SELECT metric, count(*) AS n_rows
FROM   gold.fmts_p_default
GROUP  BY metric;

-- --- huge_pages: PG-side leg of the two-leg monthly check (the host-side /proc/meminfo leg runs
-- from outside the DB — see the OS-level disk/hugepages check script referenced in §P1/§P2) ---
CREATE OR REPLACE FUNCTION control.check_hugepages() RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_status text;
BEGIN
  SELECT setting INTO v_status FROM pg_settings WHERE name = 'huge_pages_status';
  IF v_status IS DISTINCT FROM 'on' THEN
    INSERT INTO control.p2_pipeline_log (step, status, message)
      VALUES ('HUGEPAGES_DRIFT', 'WARN', format('huge_pages_status=%s', v_status));
  END IF;
END $$;

-- --- Disk headroom pre-flight (§P2 "Disk headroom" / §P3 seed-time equivalent). The gating check
-- itself runs from the wrapping shell/Python script (host `df` isn't visible to SQL) — this
-- function is the logging contract that script writes into, so CLUSTER_MAINT/BLOAT_ALERT and a
-- skipped-for-space event land in the same place.
CREATE OR REPLACE FUNCTION control.log_disk_headroom_skip(
  p_operation text, p_required_bytes bigint, p_available_bytes bigint
) RETURNS void LANGUAGE sql AS $$
  INSERT INTO control.p2_pipeline_log (step, status, message)
  VALUES ('DISK_HEADROOM_SKIP', 'WARN',
          format('%s skipped: required=%s available=%s',
                 p_operation, p_required_bytes, p_available_bytes));
$$;

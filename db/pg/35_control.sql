-- -----------------------------------------------------------------------------
-- control.fund_metric_state — 3,680 rows, per-fund calc fingerprint/state (P2 idempotency cache)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS control.fund_metric_state (
    isin                  varchar(12) NOT NULL,
    metric_version         text        NOT NULL DEFAULT 'v1',
    input_hash              text        NOT NULL,   -- SHA-1 hex, 40 chars
    calculated_at            date        NOT NULL,
    last_ols_quarter          text,
    last_ols_nav_count         integer,

    CONSTRAINT fund_metric_state_pkey PRIMARY KEY (isin, metric_version),
    CONSTRAINT fund_metric_state_isin_fk FOREIGN KEY (isin) REFERENCES silver.fund_master (isin) ON DELETE CASCADE
) WITH (fillfactor = 85);   -- rewritten every P2 cycle — HOT-eligible with the low secondary-index count here

-- -----------------------------------------------------------------------------
-- control.p2_pipeline_log — 575K rows, per-run traceability. Append-only.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS control.p2_pipeline_log (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isin            text,       -- NOT varchar(12): confirmed against the live server 2026-09-19,
                                 -- 1/704,727 rows holds a comma-joined list of multiple ISINs
                                 -- (a batch-level SKIP log entry, step=NAV_LOAD, 116 chars) —
                                 -- a real logging convention (batch events log all affected
                                 -- ISINs together), not corruption like kiid_lifecycle's case.
                                 -- No FK on this column (it's a diagnostic log, not a domain
                                 -- reference), so widening it has no referential-integrity impact.
    step            text,       -- NAV_LOAD / DEFLATE / CALC_METRICS / WRITE / MV_REFRESH / CLUSTER_MAINT / ...
    status           text,       -- OK / WARN / ERROR / SKIP
    horizon           text,
    metric_version     text,
    message             text,
    created_at           timestamptz DEFAULT now(),
    batch_id             text
);

CREATE INDEX IF NOT EXISTS idx_p2log_isin ON control.p2_pipeline_log (isin);
CREATE INDEX IF NOT EXISTS idx_p2log_step ON control.p2_pipeline_log (step, created_at);
CREATE INDEX IF NOT EXISTS idx_p2log_batch ON control.p2_pipeline_log (batch_id) WHERE batch_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_p2log_created_brin ON control.p2_pipeline_log
  USING brin (created_at) WITH (pages_per_range = 32);   -- 100% correlated by construction (append-only)

-- -----------------------------------------------------------------------------
